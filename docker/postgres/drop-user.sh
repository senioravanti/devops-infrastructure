#!/usr/bin/env bash
database=${DATABASE:-postgres}
PGPASSWORD="$ROOT_USER_PASSWORD" \
psql -h "${HOST:-localhost}" -p "${PORT:-5432}" \
  -U "${ROOT_USER_NAME:-postgres}" "$database" <<EOF
BEGIN;

REVOKE SELECT, INSERT, UPDATE ON ALL TABLES IN SCHEMA public FROM $NEW_USER_NAME;
REVOKE CONNECT ON DATABASE $database FROM $NEW_USER_NAME;
REVOKE USAGE ON SCHEMA public FROM $NEW_USER_NAME;
DROP USER $NEW_USER_NAME;

COMMIT;
EOF
